// ── VSOP87 EVALUATOR ──────────────────────────────────────────────────────────

function evalSeries(s: Series, tau: number): number {
  return s.reduce((acc, [A, B, C]) => acc + A * Math.cos(B + C * tau), 0)
}

function vsop87(p: VPlanet, tau: number): { L: number; B: number; R: number } {
  const L = normRad((
    evalSeries(p.L0, tau) +
    (p.L1 ? evalSeries(p.L1, tau) * tau : 0) +
    (p.L2 ? evalSeries(p.L2, tau) * tau * tau : 0) +
    (p.L3 ? evalSeries(p.L3, tau) * tau * tau * tau : 0)
  ) / 1e8)
  const B = (evalSeries(p.B0, tau) + (p.B1 ? evalSeries(p.B1, tau) * tau : 0)) / 1e8
  const R = (evalSeries(p.R0, tau) + (p.R1 ? evalSeries(p.R1, tau) * tau : 0)) / 1e8
  return { L, B, R }
}

function helioToGeoLon(pl: {L:number;B:number;R:number}, earth: {L:number;B:number;R:number}): number {
  const px = pl.R * Math.cos(pl.B) * Math.cos(pl.L)
  const py = pl.R * Math.cos(pl.B) * Math.sin(pl.L)
  const ex = earth.R * Math.cos(earth.B) * Math.cos(earth.L)
  const ey = earth.R * Math.cos(earth.B) * Math.sin(earth.L)
  return normRad(Math.atan2(py - ey, px - ex))
}

function distAU(pl: {L:number;B:number;R:number}, earth: {L:number;B:number;R:number}): number {
  const px = pl.R * Math.cos(pl.B) * Math.cos(pl.L); const py = pl.R * Math.cos(pl.B) * Math.sin(pl.L); const pz = pl.R * Math.sin(pl.B)
  const ex = earth.R * Math.cos(earth.B) * Math.cos(earth.L); const ey = earth.R * Math.cos(earth.B) * Math.sin(earth.L); const ez = earth.R * Math.sin(earth.B)
  return Math.sqrt((px-ex)**2 + (py-ey)**2 + (pz-ez)**2)
}

function nutation(T: number): number {
  const Om = toRad(125.04452 - 1934.136261 * T)
  const L  = toRad(280.4665  + 36000.7698  * T)
  const Lp = toRad(218.3165  + 481267.8813 * T)
  return (-17.20 * Math.sin(Om) - 1.32 * Math.sin(2*L) - 0.23 * Math.sin(2*Lp) + 0.21 * Math.sin(2*Om)) / 3600
}

