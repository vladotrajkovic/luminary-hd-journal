// ── MAIN EXPORT ───────────────────────────────────────────────────────────────

export function computeAllPlanets(jd: number): PlanetPositions {
  const T   = (jd - 2451545.0) / 36525.0
  const tau = T / 10.0

  const earth = vsop87(EARTH, tau)
  const dPsi  = nutation(T)

  function geoLon(planetData: VPlanet): number {
    const p0   = vsop87(planetData, tau)
    const d0   = distAU(p0, earth)
    const tauL = (T - 0.0057755183 * d0) / 10
    const pL   = vsop87(planetData, tauL)
    return norm360(toDeg(helioToGeoLon(pL, earth)) + dPsi)
  }

  const sunLon  = norm360(toDeg(earth.L) + 180 + dPsi)
  const nodes   = lunarNodes(T)

  return {
    sun:       sunLon,
    earth:     norm360(sunLon + 180),
    moon:      moonLongitude(T),
    northNode: nodes.north,
    southNode: nodes.south,
    mercury:   geoLon(MERCURY),
    venus:     geoLon(VENUS),
    mars:      geoLon(MARS),
    jupiter:   geoLon(JUPITER),
    saturn:    geoLon(SATURN),
    uranus:    geoLon(URANUS),
    neptune:   geoLon(NEPTUNE),
    pluto:     plutoLongitude(T),
  }
}
